def t(key: str, lang: str, **kw) -> str:
    """ค่าใน kw ที่เป็นฟังก์ชัน (รับ lang) จะถูกแปลตามภาษาของแต่ละฝั่ง
    เช่น t("stats_title", "both", p=lambda l: t("p_30d", l))
    → "สถิติ 30 วันล่าสุด | ສະຖິຕິ 30 ມື້ຫຼ້າສຸດ" ไม่ใช่คำแปลซ้อนกัน"""
    entry = S[key]
    if lang == "th":
        return entry[0].format(**_resolve(kw, "th"))
    if lang == "lo":
        return entry[1].format(**_resolve(kw, "lo"))
    if len(entry) > 2:
        return entry[2].format(**_resolve(kw, "both"))
    th, lo = entry[0].format(**_resolve(kw, "th")), entry[1].format(**_resolve(kw, "lo"))
    return th + (" | " if len(th) + len(lo) <= 50 else "\n") + lo


def _resolve(kw: dict, lang: str) -> dict:
    return {k: v(lang) if callable(v) else v for k, v in kw.items()}


def day_name(weekday: int, lang: str) -> str:
    """ชื่อวัน เช่น วันศุกร์ / ວັນສຸກ"""
    th, lo = f"วัน{DAYS['th'][weekday]}", f"ວັນ{DAYS['lo'][weekday]}"
    return th if lang == "th" else lo if lang == "lo" else f"{th} | {lo}"


def both(key: str, **kw) -> str:
    """ใช้กับคำอธิบายคำสั่งใน Discord ซึ่งต้องแสดงทั้งสองภาษาเสมอ (ไม่เกิน 100 ตัวอักษร)"""
    th, lo = S[key][0], S[key][1]
    return f"{th} / {lo}".format(**kw)[:100]
